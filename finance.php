$paymentsQuery = $conn->query("
    SELECT p.*, o.booking_ref, o.id as order_id, u.name as customer_name, staff.name as staff_name
    FROM payments p
    LEFT JOIN orders o ON p.order_id = o.id
    LEFT JOIN users u ON o.user_id = u.id
    LEFT JOIN users staff ON p.staff_id = staff.id
    WHERE $ledgerWhere
    ORDER BY p.id DESC
    LIMIT 100
");

// Fetch outstanding balances for Receivables tab
$receivablesQuery = $conn->query("
    SELECT o.id, o.booking_ref, o.order_date, o.start_date, o.end_date, o.status,
           o.total_amount, o.paid_amount, o.deposit_deducted,
           (o.total_amount - (o.paid_amount + o.deposit_deducted)) as balance_due,
           u.name as customer_name, u.phone as customer_phone, u.email as customer_email
    FROM orders o
    JOIN users u ON o.user_id = u.id
    WHERE o.status IN ('Approved', 'Active', 'Completed')
      AND (o.total_amount - (o.paid_amount + o.deposit_deducted)) > 0.009
    ORDER BY balance_due DESC
");

// Fetch active security deposit escrow
$escrowQuery = $conn->query("
    SELECT o.id, o.booking_ref, o.status, o.deposit_amount, o.deposit_deducted, o.deposit_refunded, o.deposit_status,
           u.name as customer_name, u.phone as customer_phone,
           (SELECT COALESCE(SUM(amount), 0) FROM payments WHERE order_id = o.id AND status = 'verified' AND payment_type = 'security_deposit') as collected_deposit
    FROM orders o
    JOIN users u ON o.user_id = u.id
    WHERE o.deposit_status IN ('held', 'partially_refunded')
       OR (o.deposit_amount > 0 AND o.status IN ('Approved', 'Active'))
    ORDER BY o.id DESC
");

